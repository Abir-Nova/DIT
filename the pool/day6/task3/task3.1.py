#absolute values 
print(f"the absolute value of 2 is {abs(2)} \n")
print(f"the absolute value of -2 is {abs(-2)} \n")
print(f"the absolute value of -3e4 is {abs(-3e4)} \n")

# round 3.14159 to two decimal places
print(f"the rounded value of 3.14159 to two decimal places = {round(3.14159, 2)}")

# Maximum value of [-42, 3e2, 666]
print( f" the maximum value of [-42, 3e2, 666] =  {max([-42, 3e2, 666])}")